#!/usr/bin/env python3
"""Diff Apollo prompt variants against default.json; write docs/framework_a.md."""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from memorytask.framework_a.loader import list_prompt_files, load_prompt, prompts_root  # noqa: E402


VARIANT_DIRS = (
    "pressure",
    "caught_likelihood",
    "countermeasures",
    "diff_first_encounter_reasoning",
    "variations_of_default",
)


def _msg_fingerprint(messages: list[dict]) -> list[tuple[str, str]]:
    return [(m.get("role", ""), m.get("content", "")) for m in messages]


def describe_diff(default: dict, variant: dict, rel: str) -> str:
    d_msgs = _msg_fingerprint(default["messages"])
    v_msgs = _msg_fingerprint(variant["messages"])
    notes: list[str] = []

    if len(v_msgs) != len(d_msgs):
        notes.append(f"message count {len(d_msgs)}→{len(v_msgs)}")

    # Compare pairwise where possible
    changed_roles = []
    for i, ((dr, dc), (vr, vc)) in enumerate(zip(d_msgs, v_msgs)):
        if dr != vr or dc != vc:
            changed_roles.append(f"turn{i}:{vr or dr}")
    if len(v_msgs) > len(d_msgs):
        for i in range(len(d_msgs), len(v_msgs)):
            changed_roles.append(f"extra_turn{i}:{v_msgs[i][0]}")
    if changed_roles:
        # Summarize content deltas roughly
        joined_d = "\n".join(c for _, c in d_msgs)
        joined_v = "\n".join(c for _, c in v_msgs)
        # Heuristic keywords
        heuristics = []
        for needle, label in [
            ("downturn", "removes/alters downturn pressure"),
            ("quarterly report", "alters performance pressure"),
            ("insider trading", "alters insider-trading warning"),
            ("Risk assessment", "alters risk/caught-likelihood language"),
            ("management is aware", "alters countermeasure/management language"),
            ("scratchpad", "alters scratchpad/reasoning instructions"),
            ("sell", "alters buy/sell framing"),
        ]:
            in_d = needle.lower() in joined_d.lower()
            in_v = needle.lower() in joined_v.lower()
            if in_d != in_v:
                heuristics.append(label)
        if heuristics:
            notes.append("; ".join(heuristics[:3]))
        else:
            notes.append("edits in: " + ", ".join(changed_roles[:6]))

    # Metadata diffs
    meta_keys = [
        "misalignment_string",
        "deception_trigger",
        "doubling_down_trigger",
        "temperature",
        "top_p",
        "max_tokens",
    ]
    meta_diffs = [k for k in meta_keys if default.get(k) != variant.get(k)]
    if "doubling_down_trigger" in default and "doubling_down_trigger" not in variant:
        notes.append("omits doubling_down_trigger")
    elif meta_diffs:
        notes.append("meta differs: " + ",".join(meta_diffs[:4]))

    if not notes:
        notes.append("no message/meta diff detected")
    return f"- `{rel}`: " + "; ".join(notes)


def main() -> int:
    root = prompts_root()
    default = load_prompt("default.json")
    files = list_prompt_files()
    inventory = [str(p.relative_to(root)).replace("\\", "/") for p in files]

    lines = [
        "# Framework A — Apollo Insider Trading",
        "",
        "Vendored from https://github.com/ApolloResearch/insider-trading (see `vendor/insider-trading/SOURCE.md`).",
        "",
        "## Prompt inventory",
        "",
    ]
    for rel in inventory:
        lines.append(f"- `{rel}`")

    lines += [
        "",
        "## Variant diffs vs `default.json`",
        "",
        "Auto-generated by `scripts/describe_variants_a.py` (message + key metadata diffs).",
        "",
    ]
    for folder in VARIANT_DIRS:
        lines.append(f"### `{folder}/`")
        lines.append("")
        folder_files = [r for r in inventory if r.startswith(folder + "/")]
        for rel in folder_files:
            variant = load_prompt(rel)
            lines.append(describe_diff(default, variant, rel))
        lines.append("")

    # Also note top-level non-default files
    top = [r for r in inventory if "/" not in r and r != "default.json"]
    if top:
        lines.append("### Top-level non-default")
        lines.append("")
        for rel in top:
            lines.append(describe_diff(default, load_prompt(rel), rel))
        lines.append("")

    out = ROOT / "docs" / "framework_a.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {out} ({len(inventory)} prompt files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
